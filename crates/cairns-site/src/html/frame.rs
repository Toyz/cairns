/// Where a license is read: the project's own license file in its
/// repository, when there is one license and one file; a Creative Commons
/// license's deed; otherwise the SPDX list's page for it.
pub(crate) fn license_url(log: &Log, id: &str) -> String {
    let id = id.trim();
    // The repository's own file for it: the one whose text is this license,
    // or the only one there is when the code has one license.
    if let Some(repo) = log.project.repository.as_deref() {
        let files = &log.project.license_files;
        let own = files
            .iter()
            .find(|file| file.license.as_deref() == Some(id))
            .or_else(|| match files.as_slice() {
                [only] if log.project.license.as_deref().map(str::trim) == Some(id) => Some(only),
                _ => None,
            });
        if let Some(file) = own {
            return format!("{}/blob/HEAD/{}", repo.trim_end_matches('/'), file.path);
        }
    }
    if id == "CC0-1.0" {
        return "https://creativecommons.org/publicdomain/zero/1.0/".to_string();
    }
    // `CC-BY-NC-SA-2.0-UK`: the kind, the version, and the jurisdiction a
    // license before 4.0 may have been ported to - each a part of its address.
    if let Some(rest) = id.strip_prefix("CC-") {
        let parts: Vec<&str> = rest.split('-').collect();
        if let Some(at) = parts.iter().position(|part| part.contains('.')) {
            let mut address = format!(
                "https://creativecommons.org/licenses/{}/{}/",
                parts[..at].join("-").to_lowercase(),
                parts[at]
            );
            if let Some(place) = parts.get(at + 1) {
                address.push_str(&place.to_lowercase());
                address.push('/');
            }
            return address;
        }
    }
    format!("https://spdx.org/licenses/{id}.html")
}

/// An SPDX expression with each license in it linked: `MIT OR Apache-2.0`.
pub(crate) fn license_expression_html(log: &Log, expression: &str) -> String {
    expression
        .split_whitespace()
        .map(|word| match word {
            "OR" | "AND" | "WITH" | "(" | ")" => escape(word),
            id => {
                let bare = id.trim_matches(|c| c == '(' || c == ')');
                id.replace(
                    bare,
                    &format!(
                        "<a href=\"{}\">{}</a>",
                        escape(&license_url(log, bare)),
                        escape(bare)
                    ),
                )
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

/// The footer's licenses: "Text and code MIT", or "Text CC-BY-4.0 · Code MIT"
/// when the text is licensed apart from the code - which is the point of
/// saying so on a page made of text. Nothing when no license is known.
pub(crate) fn licenses_html(log: &Log) -> String {
    let Some(code) = log.project.license.as_deref() else {
        return match log.project.text_license.as_deref() {
            Some(text) => format!("Text {}. ", license_expression_html(log, text)),
            None => String::new(),
        };
    };
    match log.project.text_license.as_deref() {
        Some(text) => format!(
            "Text {} \u{00b7} Code {}. ",
            license_expression_html(log, text),
            license_expression_html(log, code)
        ),
        None => format!("Text and code {}. ", license_expression_html(log, code)),
    }
}

/// `<link rel="license">` for the page's own content - the text - when its
/// license is a single one with a page to point at.
pub(crate) fn license_link(log: &Log) -> String {
    let text = log
        .project
        .text_license
        .as_deref()
        .or(log.project.license.as_deref());
    match text {
        Some(id) if !id.contains(char::is_whitespace) => {
            format!(
                "\n<link rel=\"license\" href=\"{}\">",
                escape(&license_url(log, id))
            )
        }
        _ => String::new(),
    }
}

/// "cairns 0.10.1", linking to that release - so a reader, or whoever keeps
/// the site, can tell which version made a page without opening `log.json`.
/// A build from source says so rather than showing a version it is not.
pub(crate) fn generator_html(generator: &str) -> String {
    let version = generator.strip_prefix("cairns ").unwrap_or(generator);
    if version.is_empty() || version.contains("dev") {
        return "<a href=\"https://github.com/Toyz/cairns\">cairns</a> (a development build)"
            .to_string();
    }
    // `git describe` past a release: `0.10.1-2-gf958c93` - the release, how
    // many commits beyond it, and the commit itself, which is what it links to.
    let parts: Vec<&str> = version.rsplitn(3, '-').collect();
    if let [commit, count, release] = parts.as_slice()
        && let Some(commit) = commit.strip_prefix('g')
        && count.chars().all(|c| c.is_ascii_digit())
    {
        return format!(
            "<a href=\"https://github.com/Toyz/cairns/commit/{commit}\">cairns {release} + {count} \
             commit{plural}</a>",
            plural = if *count == "1" { "" } else { "s" },
            commit = escape(commit),
            release = escape(release),
            count = escape(count)
        );
    }
    format!(
        "<a href=\"https://github.com/Toyz/cairns/releases/tag/v{v}\">cairns {v}</a>",
        v = escape(version)
    )
}

#[cfg(test)]
mod footer_tests {
    use super::generator_html;

    #[test]
    fn the_footer_names_the_version_that_made_the_page() {
        assert_eq!(
            generator_html("cairns 0.10.1"),
            "<a href=\"https://github.com/Toyz/cairns/releases/tag/v0.10.1\">cairns 0.10.1</a>"
        );
        assert!(generator_html("cairns 0.0.0-dev").contains("development build"));
        assert_eq!(
            generator_html("cairns 0.10.1-2-gf958c93"),
            "<a href=\"https://github.com/Toyz/cairns/commit/f958c93\">cairns 0.10.1 + 2 commits</a>"
        );
    }
}
